const box = (text: string, tone?: "info" | "good" | "bad"): Block => ({ t: "box", text, tone })
const list = (items: string[], ordered = false): Block => ({ t: "list", items, ordered })
const tags = (items: string[]): Block => ({ t: "tags", items })
const table = (head: string[], rows: string[][]): Block => ({ t: "table", head, rows })

