export type Block =
  | { t: "p"; text: string }
  | { t: "h4"; text: string }
  | { t: "box"; text: string; tone?: "info" | "good" | "bad" }
  | { t: "list"; items: string[]; ordered?: boolean }
  | { t: "tags"; items: string[] }
  | { t: "table"; head: string[]; rows: string[][] }

export type Section = { id: string; title: string; blocks: Block[] }
export type Chapter = { id: string; num: string; title: string; color: string; sections: Section[] }

const p = (text: string): Block => ({ t: "p", text })
